function Tt = tl_drawing_table(in, D, G, F, P, A)
%TL_DRAWING_TABLE  Tolerance and fits table for the 3.9 drawings (EN and TR text).
%   Tt = tl_drawing_table(in, D, G, F, P, A)
%   D = tl_datums, G = tl_gears, F = tl_fits, P = tl_splines, A = tl_axial
%   One row per drawing callout: part, feature (EN, TR), callout (EN, TR), value, basis. Geometric
%   tolerances from E1, gear data from E6, fits from E4 (ISO 286 classes or limit dimensions), splines from
%   E5, axial gaps from E3c, and the drawing notes the stack-ups need.
%   Source: Phase 3 report, Section 3.8.

r = {};
add = @(part, f_en, f_tr, c_en, c_tr, v, basis) {string(part), string(f_en), string(f_tr), string(c_en), string(c_tr), ...
                                                  string(v), string(basis)};
tr_ch = containers.Map({'cylindricity', 'datum feature', 'radial runout (F_r)', 'total runout (axial)', 'axial runout', ...
                        'position (axial)', 'size spread within the set', 'perpendicularity', 'position (diametral zone)', ...
                        'parallelism to A-B over the pin length', 'total runout', 'flatness', ...
                        'parallelism to the pinion axis, over the 102 mm span'}, ...
                       {'silindiriklik', 'referans unsuru', 'radyal salgı (F_r)', 'toplam salgı (eksenel)', 'eksenel salgı', ...
                        'konum (eksenel)', 'takım içinde boyut farkı', 'diklik', 'konum (çap bölgesi)', ...
                        'pim boyunca A-B''ye paralellik', 'toplam salgı', 'düzlemsellik', ...
                        'pinyon eksenine paralellik, 102 mm açıklıkta'});
for k = 1:height(D.T)
    v = D.T.tolerance_mm(k);
    if isnan(v), vs = string(D.T.datums(k)); else, vs = sprintf('%.3f mm | %s', v, D.T.datums(k)); end
    r(end + 1, :) = add(D.T.part(k), D.T.feature_en(k), D.T.feature_tr(k), D.T.characteristic(k), ...
                        tr_ch(char(D.T.characteristic(k))), vs, D.T.basis(k)); %#ok<AGROW>
end
for k = 1:height(G.T)
    g = G.T(k, :);
    r(end + 1, :) = add(g.gear, 'teeth', 'dişler', 'ISO 1328-1:2013 class (pitch, helix / profile)', ...
        'ISO 1328-1:2013 sınıfı (adım, helis / profil)', sprintf('%d / %d', g.class, g.class_profile), 'E6'); %#ok<AGROW>
    r(end + 1, :) = add(g.gear, 'teeth', 'dişler', 'tooth thickness allowance E_sns / E_sni (ring: space width)', ...
        'diş kalınlığı payı E_sns / E_sni (halka: boşluk genişliği)', sprintf('%+d / %+d um', g.E_sns_um, g.E_sni_um), 'E3 backlash'); %#ok<AGROW>
end
r(end + 1, :) = add('Sun P105, planets P107', 'profile modification', 'profil düzeltmesi', 'amplitude tolerance', ...
    'genlik toleransı', sprintf('+-%g um', in.tip_relief_tol), 'STR-11 (3.9 LTCA)');
for b = 1:numel(in.brg)
    br = in.brg(b);
    r(end + 1, :) = add(br.name, 'bearing seat on the shaft / in the liner', 'mildeki / gömlekteki rulman yuvası', ...
        'ISO 286 classes', 'ISO 286 sınıfları', sprintf('dia %g %s / dia %g %s', br.d, br.shaft, br.D, br.housing), 'E4'); %#ok<AGROW>
    if any(br.c0)
        r(end + 1, :) = add(br.name, 'radial internal clearance before mounting', 'montaj öncesi radyal iç boşluk', ...
            'clearance group', 'boşluk grubu', sprintf('%.3f-%.3f mm', br.c0), 'E4, TBR supplier'); %#ok<AGROW>
    end
end
for l = 1:numel(in.liner)
    ln = in.liner(l);
    r(end + 1, :) = add(sprintf('Steel liner (%s) in the A357 boss', ln.name), 'liner OD in the boss', 'göbekteki gömlek dış çapı', ...
        'radial interference at 20 degC', '20 °C''de radyal sıkılık', sprintf('%.4f-%.4f mm', ln.delta), 'step 3.5, E4'); %#ok<AGROW>
    r(end + 1, :) = add(sprintf('Steel liner (%s) in the A357 boss', ln.name), 'liner bore', 'gömlek deliği', ...
        'drawing note', 'resim notu', 'finish-bore after shrinking into the casting', 'E4 (bearing clearance)'); %#ok<AGROW>
end
r(end + 1, :) = add('Carrier P103 / planet pins P104', 'pin in the plate (dia 38)', 'plakadaki pim (çap 38)', 'ISO 286 fit', ...
    'ISO 286 geçme', sprintf('%s', F.pin.fit), 'E4');
r(end + 1, :) = add('Planetary case P101 / ring gear P102', 'ring gear seat dia 259', 'halka dişli yuvası çap 259', ...
    'limit dimensions (bore / ring)', 'sınır ölçüleri (delik / halka)', sprintf('bore %+d / %+d um, ring %s', ...
    in.seat.bore_dev(2), in.seat.bore_dev(1), in.seat.cls_ring), 'E4, DYN-03 (3.6)');
r(end + 1, :) = add('Planetary case P101 / ring gear P102', 'assembly', 'montaj', 'drawing note', 'resim notu', ...
    sprintf('heat the case to 110 +- 10 degC (at least %.0f degC; never above %.0f degC)', F.T_assy, in.seat.T_age), 'E4');
for k = 1:numel(in.spl)
    sp = in.spl(k);
    row = P.T(P.T.spline == sp.name, :);
    r(end + 1, :) = add(sp.name, 'involute spline, 30 deg, flat root', 'evolvent kama, 30°, düz dip', 'ISO 4156-1 fit and class', ...
        'ISO 4156-1 geçme ve sınıf', sprintf('m %g, z %d, %s', sp.m, sp.z, row.fit(1)), 'E5'); %#ok<AGROW>
end
r(end + 1, :) = add('Bearing housing P111 / carrier P103', 'catcher-lip axial gap at 20 degC', '20 °C''de yakalama dudağı eksenel boşluğu', ...
    'gap', 'boşluk', sprintf('%.2f-%.2f mm', in.ax.lip_gap), sprintf('E3c (never touching; catches within %.2f mm)', A.max_lip_travel));
r(end + 1, :) = add('Retention tube P114 / propeller hub', 'anchor axial clearance at 20 degC', '20 °C''de bağlantı eksenel boşluğu', ...
    'clearance', 'boşluk', sprintf('%.2f-%.2f mm', in.ax.tube_gap), sprintf('E3c (stays open; catches within %.2f mm)', A.max_tube_travel));
Tt = cell2table(r, 'VariableNames', {'part', 'feature_en', 'feature_tr', 'callout_en', 'callout_tr', 'value', 'basis'});
end
