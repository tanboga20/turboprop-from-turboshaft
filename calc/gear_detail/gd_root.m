function r = gd_root(z, mn, beta_deg, x, d_Na, eps_alpha, eps_beta, tool, internal, alpha_n_deg)
%GD_ROOT  Tooth form factor Y_F and stress correction factor Y_S by ISO 6336-3:2019 Method B.
%   r = gd_root(z, mn, beta_deg, x, d_Na, eps_alpha, eps_beta, tool, internal, alpha_n_deg)
%
%   Inputs
%     z           number of teeth, positive (internal gears are flagged)    [-]
%     mn          normal module                                             [mm]
%     beta_deg    helix angle                                               [deg]
%     x           profile shift coefficient (ISO sign convention: for an
%                 internal gear a positive x thickens the tooth)           [-]
%     d_Na        effective tip diameter, positive                          [mm]
%     eps_alpha   transverse contact ratio of the mesh                      [-]
%     eps_beta    overlap ratio of the mesh                                 [-]
%     tool        hob: struct with hfP, rhofP, spr (in modules);
%                 shaper cutter: struct with z0, x0, haP0, rhoa0, spr
%                 (haP0, rhoa0, spr in modules)
%     internal    true for the ring (shaper cutter, 60 deg tangent)
%     alpha_n_deg normal pressure angle                                     [deg]
%
%   Output struct r: Y_F, Y_S, f_eps; virtual gear zn, eps_an, d_en, alpha_en,
%   gamma_e, alpha_Fen [rad]; root values s_Fn, h_Fe, rho_F [mm], q_s, L;
%   theta (hob: the angle of Formula (29); shaper: the tangent angle) [rad];
%   d_f (root diameter generated by the tool, positive) [mm].
%
%   Virtual gear: Formulae (15) to (25). Hob: Formulae (26) to (32), load at
%   the outer point of single pair tooth contact of the virtual spur gear.
%   Shaper cutter: Formulae (33) to (61); internal gears take negative z, d
%   and d_Na, as the standard prescribes. Y_S: Formulae (62) to (64).
%   Source: Phase 2 report, Section 2.4 ("Tooth root"). Tested by
%   test_step24 (TC33), against a numerical simulation of the generating
%   cut in calc/reference/step24_reference.py.

an = deg2rad(alpha_n_deg);
beta = deg2rad(beta_deg);
inv = @(a) tan(a) - a;
sgn = 1;
if internal, sgn = -1; end
zs = sgn * z;                                % signed number of teeth
d = zs * mn / cos(beta);                     % signed reference diameter
dNa = sgn * d_Na;

% Virtual gear, Formulae (15) to (25)
bb = asin(sin(beta) * cos(an));
zn = zs / (cos(bb)^2 * cos(beta));
ean = eps_alpha / cos(bb)^2;
dn = d / cos(bb)^2;
dbn = dn * cos(an);
dan = dn + dNa - d;
d_en = 2 * sgn * sqrt((sqrt((dan / 2)^2 - (dbn / 2)^2) ...
       - pi * d * cos(beta) * cos(an) / abs(zs) * (ean - 1))^2 + (dbn / 2)^2);
a_en = acos(dbn / d_en);
g_e = (0.5 * pi + 2 * x * tan(an)) / zn + inv(an) - inv(a_en);
a_Fen = a_en - g_e;

if ~internal
    % External gear generated with a hob, Formulae (26) to (32)
    hfP = tool.hfP * mn;
    rfP = tool.rhofP * mn;
    spr = tool.spr * mn;
    E = pi / 4 * mn - hfP * tan(an) + spr / cos(an) - (1 - sin(an)) * rfP / cos(an);
    G = rfP / mn - hfP / mn + x;
    H = 2 / zn * (pi / 2 - E / mn) - pi / 3;
    th = pi / 6;
    for k = 1:100
        th_new = 2 * G / zn * tan(th) - H;
        if abs(th_new - th) < 1e-13, th = th_new; break, end
        th = th_new;
    end
    s_Fn = mn * (zn * sin(pi / 3 - th) + sqrt(3) * (G / cos(th) - rfP / mn));
    rho_F = mn * (rfP / mn + 2 * G^2 / (cos(th) * (zn * cos(th)^2 - 2 * G)));
    h_Fe = mn / 2 * ((cos(g_e) - sin(g_e) * tan(a_Fen)) * d_en / mn - zn * cos(pi / 3 - th) ...
                     - G / cos(th) + rfP / mn);
    d_f = abs(d) - 2 * (hfP - x * mn);
else
    % Internal gear generated with a shaper cutter, Formulae (33) to (61)
    th = pi / 3;                             % 60 deg tangent for an internal gear
    z0v = tool.z0 / (cos(beta) * cos(bb)^2);
    haP0 = tool.haP0 * mn;
    ra0 = tool.rhoa0 * mn;
    spr = tool.spr * mn;
    xi = 2 * (tool.x0 + x) / (z0v + zn) * tan(an) + inv(an);
    aw0 = (3 * xi)^(1/3);
    for k = 1:100
        step = (xi - inv(aw0)) / tan(aw0)^2;
        aw0 = aw0 + step;
        if abs(step) < 1e-15, break, end
    end
    a0 = mn * (z0v + zn) / 2 * cos(an) / cos(aw0);
    u0 = z0v / zn;
    rw = a0 / (1 + u0);
    rw0 = rw * u0;
    rb0 = 0.5 * mn * z0v * cos(an);
    rM = mn * (z0v / 2 + haP0 / mn + tool.x0 - ra0 / mn);
    aM = acos(rb0 / rM);
    dalpha = (0.5 * pi + 2 * tool.x0 * tan(an)) / z0v - (ra0 - spr) / rb0 + inv(an) - inv(aM);
    YM = rM * cos(dalpha);
    psi0 = pi / zn + th;
    psi = psi0;
    for k = 1:100
        lam = rw0 / rM * cos(psi);
        y = psi - acos(lam) + dalpha + (psi - psi0) / u0;
        yp = 1 + 1 / u0 - rw0 / rM * sin(psi) / sqrt(1 - lam^2);
        psi = psi - y / yp;
        if abs(y / yp) < 1e-13, break, end
    end
    delta = acos(rw0 / rM * cos(psi));
    w0 = delta - psi - dalpha;
    dh1 = YM - rw0 * cos(w0);
    dh = dh1 * sin(psi) / sin(psi + w0);
    K = dh / sin(psi);
    X = rw * sin(psi - th) - (K + ra0) * cos(th);
    Y = rw * cos(psi - th) - (K + ra0) * sin(th);
    s_Fn = 2 * X;
    rho_F = K^2 / (rw0 * rw / (rw0 + rw) * sin(psi) + K) + ra0;
    h_Fe = (cos(g_e) - sin(g_e) * tan(a_Fen)) * d_en / 2 - Y;
    d_f = 2 * (abs(a0) + rM + ra0) * cos(bb)^2;   % cutter tip circle on the virtual gear; exact for spur gears
end

% Y_F and Y_S, Formulae (9) to (14) and (62) to (64)
if eps_beta <= 0
    if ean < 2, f_eps = 1; else, f_eps = 0.7; end
elseif eps_beta < 1
    if ean < 2
        f_eps = sqrt(1 - eps_beta + eps_beta / ean);
    else
        f_eps = sqrt((1 - eps_beta) / 2 + eps_beta / ean);
    end
else
    f_eps = ean^-0.5;
end
Y_F = 6 * (h_Fe / mn) * cos(a_Fen) / ((s_Fn / mn)^2 * cos(an)) * f_eps;
q_s = s_Fn / (2 * rho_F);
L = s_Fn / h_Fe;
Y_S = (1.2 + 0.13 * L) * q_s^(1 / (1.21 + 2.3 / L));
r = struct('Y_F', Y_F, 'Y_S', Y_S, 'f_eps', f_eps, 'zn', zn, 'eps_an', ean, 'd_en', abs(d_en), ...
           'alpha_en', a_en, 'gamma_e', g_e, 'alpha_Fen', a_Fen, 'theta', th, ...
           's_Fn', s_Fn, 'h_Fe', h_Fe, 'rho_F', rho_F, 'q_s', q_s, 'L', L, 'd_f', d_f);
end
